BASE_DIR = r"D:\Obsidian-Knowledge\qimendunjia\奇门遁甲知识库\.原始笔记"
OUTPUT_DIR = r"D:\Obsidian-Knowledge\qimendunjia\.ocr_fixed"

# 确保输出目录存在
os.makedirs(OUTPUT_DIR, exist_ok=True)

def fix_ocr(text):
    """逐字符替换 OCR 错误"""
    result = []
    for ch in text:
        if ch in OCR_MAP:
            result.append(OCR_MAP[ch])
        else:
            result.append(ch)
    return ''.join(result)

def process_folder(folder_name):
    """处理单个笔记文件夹"""
    # 构建路径
    # 例如: 179.奇门遁甲奇门穿壬第七集_笔记/179.奇门遁甲奇门穿壬第七集_笔记/auto/179.奇门遁甲奇门穿壬第七集_笔记.md
    nested = os.path.join(BASE_DIR, folder_name, folder_name, "auto")
    md_file = os.path.join(nested, folder_name + ".md")

    if not os.path.exists(md_file):
        # 尝试另一种路径模式
        alt_path = os.path.join(BASE_DIR, folder_name, "auto", folder_name + ".md")
        if os.path.exists(alt_path):
            md_file = alt_path
        else:
            print(f"  [SKIP] 找不到文件: {folder_name}")
            return None

    print(f"  处理: {folder_name}")
    with open(md_file, 'r', encoding='utf-8') as f:
        content = f.read()

    fixed = fix_ocr(content)

    # 保存到临时输出目录
    out_path = os.path.join(OUTPUT_DIR, folder_name + "_ocr_fixed.md")
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(fixed)

    # 统计替换情况
    changes = sum(1 for a, b in zip(content, fixed) if a != b)
    print(f"    OCR 替换: {changes} 处")

    return out_path

def main():
    # 获取所有待处理的文件夹 (179-221)
    all_folders = sorted(os.listdir(BASE_DIR))
    target_folders = []

    for f in all_folders:
        # 匹配 179. 到 221. 开头的文件夹
        match = re.match(r'^(1[7-9]\d|2[01]\d|22[01])\.', f)
        if match:
            num = int(match.group(1))
            if 179 <= num <= 221:
                target_folders.append(f)

    print(f"找到 {len(target_folders)} 个待处理文件夹 (179-221)")
    print("=" * 60)

    for folder in target_folders:
        process_folder(folder)

    print("=" * 60)
    print(f"OCR 批量修正完成，输出目录: {OUTPUT_DIR}")

if __name__ == '__main__':
    main()
